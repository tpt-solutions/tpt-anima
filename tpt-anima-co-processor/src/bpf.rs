//! eBPF kernel module for Linux workload interception.
//!
//! This module hand-assembles real eBPF bytecode for the programs used to intercept AI
//! workloads at the kernel level. The instruction encoding follows the Linux kernel's
//! `struct bpf_insn` layout (see `linux/bpf.h` / `linux/filter.h`):
//!
//! ```text
//! struct bpf_insn {
//!     __u8  code;      // opcode
//!     __u8  dst_reg:4; // destination register (low nibble)
//!     __u8  src_reg:4; // source register (high nibble)
//!     __s16 off;       // signed offset, little-endian
//!     __s32 imm;       // signed immediate, little-endian
//! };
//! ```
//!
//! Each instruction is exactly 8 bytes. `BPF_LD | BPF_DW | BPF_IMM` (used for 64-bit
//! immediates / map file descriptors) is a "wide" instruction that occupies two
//! consecutive 8-byte slots (16 bytes total), but none of the programs generated here
//! need it — they are intentionally minimal, verifier-friendly programs.
//!
//! The bytecode generated by this module has NOT been loaded against a live Linux
//! kernel/verifier from this development environment (no Linux kernel is available on
//! this Windows machine). The encoding below has been hand-checked instruction-by-
//! instruction against the public eBPF ISA reference and the opcode constants in
//! `linux/bpf.h`, and is covered by structural unit tests, but it is unverified end to
//! end against `bpf(BPF_PROG_LOAD, ...)`. See `crate::driver` for the Linux-only load
//! path, which carries the same caveat.

use serde::{Deserialize, Serialize};

/// An eBPF program definition for workload interception.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EbpfProgram {
    /// Program name/identifier.
    pub name: String,
    /// eBPF bytecode (compiled from restricted C/Rust).
    pub bytecode: Vec<u8>,
    /// Map definitions for the program.
    pub maps: Vec<EbpfMap>,
}

/// An eBPF map definition.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EbpfMap {
    /// Map name.
    pub name: String,
    /// Map type (hash, array, etc.).
    pub map_type: EbpfMapType,
    /// Key size in bytes.
    pub key_size: u32,
    /// Value size in bytes.
    pub value_size: u32,
}

/// eBPF map types.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum EbpfMapType {
    /// Hash map.
    Hash,
    /// Array map.
    Array,
    /// Per-CPU array.
    PerCpuArray,
    /// Queue.
    Queue,
    /// Stack.
    Stack,
}

/// Hook points where eBPF programs can attach.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum HookPoint {
    /// Tracepoint for syscall entry.
    SyscallEntry,
    /// Tracepoint for syscall exit.
    SyscallExit,
    /// Kprobe (kernel function entry).
    Kprobe,
    /// Kretprobe (kernel function return).
    Kretprobe,
    /// Uprobe (user function entry).
    Uprobe,
    /// Network interface receive.
    NetDevQueue,
}

// ---------------------------------------------------------------------------------
// eBPF instruction encoding
// ---------------------------------------------------------------------------------
//
// Instruction classes (low 3 bits of `code` for non-ALU/JMP, or bits [0:2]):
const BPF_LDX: u8 = 0x01;
const BPF_ALU64: u8 = 0x07;
const BPF_JMP: u8 = 0x05;

// Size modifiers (bits [3:4] of `code`), used with BPF_LDX/BPF_STX/BPF_ST/BPF_LD:
const BPF_W: u8 = 0x00; // 32-bit word
const BPF_H: u8 = 0x08; // 16-bit half-word

// Mode modifier for load/store from a register-held address:
const BPF_MEM: u8 = 0x60;

// ALU/JMP "source" operand modifiers (bit 3 of `code`):
const BPF_K: u8 = 0x00; // use 32-bit immediate
#[allow(dead_code)] // kept for documentation completeness of the ISA subset used here
const BPF_X: u8 = 0x08; // use src_reg

// ALU/JMP operations (high 4 bits of `code`):
const BPF_MOV: u8 = 0xb0;
const BPF_ADD: u8 = 0x00;
const BPF_AND: u8 = 0x50;
const BPF_JEQ: u8 = 0x10;
const BPF_JNE: u8 = 0x50;
const BPF_EXIT: u8 = 0x90;

// Registers.
const R0: u8 = 0; // return value
const R1: u8 = 1; // first argument (context pointer on entry)
const R2: u8 = 2;

/// A single 8-byte eBPF instruction, encoded per `struct bpf_insn`.
///
/// This is a thin builder used only to assemble the byte-level programs below; it is
/// intentionally minimal rather than a general-purpose eBPF assembler.
struct Insn {
    code: u8,
    dst_reg: u8,
    src_reg: u8,
    off: i16,
    imm: i32,
}

impl Insn {
    fn to_bytes(&self) -> [u8; 8] {
        let mut buf = [0u8; 8];
        buf[0] = self.code;
        // dst_reg occupies the low nibble, src_reg the high nibble.
        buf[1] = (self.dst_reg & 0x0f) | ((self.src_reg & 0x0f) << 4);
        buf[2..4].copy_from_slice(&self.off.to_le_bytes());
        buf[4..8].copy_from_slice(&self.imm.to_le_bytes());
        buf
    }

    /// `ALU64: dst = imm` — e.g. `mov64 r0, imm`.
    fn mov64_imm(dst: u8, imm: i32) -> Self {
        Self {
            code: BPF_ALU64 | BPF_MOV | BPF_K,
            dst_reg: dst,
            src_reg: 0,
            off: 0,
            imm,
        }
    }

    /// `ALU64: dst += imm`.
    fn add64_imm(dst: u8, imm: i32) -> Self {
        Self {
            code: BPF_ALU64 | BPF_ADD | BPF_K,
            dst_reg: dst,
            src_reg: 0,
            off: 0,
            imm,
        }
    }

    /// `ALU64: dst &= imm`.
    fn and64_imm(dst: u8, imm: i32) -> Self {
        Self {
            code: BPF_ALU64 | BPF_AND | BPF_K,
            dst_reg: dst,
            src_reg: 0,
            off: 0,
            imm,
        }
    }

    /// `LDX: dst = *(u32 *)(src + off)` — word-sized context/struct field load.
    fn ldx_w(dst: u8, src: u8, off: i16) -> Self {
        Self {
            code: BPF_LDX | BPF_MEM | BPF_W,
            dst_reg: dst,
            src_reg: src,
            off,
            imm: 0,
        }
    }

    /// `LDX: dst = *(u16 *)(src + off)` — half-word-sized context/struct field load.
    fn ldx_h(dst: u8, src: u8, off: i16) -> Self {
        Self {
            code: BPF_LDX | BPF_MEM | BPF_H,
            dst_reg: dst,
            src_reg: src,
            off,
            imm: 0,
        }
    }

    /// `JMP: if dst == imm goto +off`.
    fn jeq_imm(dst: u8, imm: i32, off: i16) -> Self {
        Self {
            code: BPF_JMP | BPF_JEQ | BPF_K,
            dst_reg: dst,
            src_reg: 0,
            off,
            imm,
        }
    }

    /// `JMP: if dst != imm goto +off`.
    fn jne_imm(dst: u8, imm: i32, off: i16) -> Self {
        Self {
            code: BPF_JMP | BPF_JNE | BPF_K,
            dst_reg: dst,
            src_reg: 0,
            off,
            imm,
        }
    }

    /// `JMP: exit` — returns the value currently in r0 to the caller/verifier.
    fn exit() -> Self {
        Self {
            code: BPF_JMP | BPF_EXIT,
            dst_reg: 0,
            src_reg: 0,
            off: 0,
            imm: 0,
        }
    }
}

/// Assemble a sequence of instructions into a flat byte buffer (8 bytes each).
fn assemble(insns: &[Insn]) -> Vec<u8> {
    let mut bytes = Vec::with_capacity(insns.len() * 8);
    for insn in insns {
        bytes.extend_from_slice(&insn.to_bytes());
    }
    bytes
}

impl EbpfProgram {
    /// Generate real eBPF bytecode for the inference-intercept tracepoint program.
    ///
    /// Semantics: this is written as a tracepoint-style program (e.g. attached to a
    /// `raw_syscalls:sys_enter` or a kprobe on an inference entry point) whose context
    /// (`r1`) is a pointer to the trace record. The program:
    ///
    /// 1. Loads the syscall/entry number field (word at context offset 0) into `r2`.
    /// 2. Masks it against a sentinel so downstream verifier analysis has a concrete,
    ///    bounded value to reason about (`r2 &= 0xff`) — a common defensive pattern in
    ///    real tracepoint programs to keep values in range before using them as map
    ///    keys or verdicts.
    /// 3. Compares the masked value against 0. If it's zero (no event id), returns 0
    ///    to skip recording; otherwise falls through.
    /// 4. Sets `r0 = 1` (accept / record-this-event verdict) and exits.
    ///
    /// This mirrors the classic minimal accept/pass pattern (`r0 = 1; exit;`) while
    /// actually touching the `intercept_events` map's natural key field (event id) so
    /// the program has real, non-trivial control flow a verifier can walk.
    pub fn generate_inference_intercept() -> Self {
        let insns = vec![
            // r2 = *(u32 *)(r1 + 0)   -- load event id from context
            Insn::ldx_w(R2, R1, 0),
            // r2 &= 0xff              -- bound the value
            Insn::and64_imm(R2, 0xff),
            // if r2 == 0 goto +2      -- skip to "drop" path
            Insn::jeq_imm(R2, 0, 2),
            // r0 = 1                  -- accept verdict
            Insn::mov64_imm(R0, 1),
            // goto +1                 -- jump over the drop path to exit
            Insn {
                code: BPF_JMP,
                dst_reg: 0,
                src_reg: 0,
                off: 1,
                imm: 0,
            },
            // r0 = 0                  -- drop verdict (event id was 0)
            Insn::mov64_imm(R0, 0),
            // exit
            Insn::exit(),
        ];

        Self {
            name: "anima_inference_intercept".to_string(),
            bytecode: assemble(&insns),
            maps: vec![EbpfMap {
                name: "intercept_events".to_string(),
                map_type: EbpfMapType::Hash,
                key_size: 8,
                value_size: 64,
            }],
        }
    }

    /// Generate real eBPF bytecode for the memory-trace program.
    ///
    /// Semantics: attached at a memory-allocation tracepoint/kprobe whose context
    /// carries the allocation size as a 16-bit field at offset 8 (a plausible layout
    /// for a `kmalloc`-style trace record: pointer-ish fields first, size field
    /// after). The program:
    ///
    /// 1. Loads the half-word size field from the context.
    /// 2. Adds a fixed per-event accounting overhead constant to it (an example of the
    ///    kind of lightweight, verifier-safe arithmetic a memory-trace program does
    ///    before handing a value to a per-CPU array map, mirroring `memory_events`'s
    ///    per-CPU accounting role).
    /// 3. Compares against a threshold; large allocations get verdict 2 (flagged),
    ///    everything else gets verdict 1 (recorded normally).
    /// 4. Exits with that verdict in `r0`.
    pub fn generate_memory_trace() -> Self {
        const SMALL_ALLOC_OVERHEAD: i32 = 16;
        const LARGE_ALLOC_THRESHOLD: i32 = 4096;

        let insns = vec![
            // r2 = *(u16 *)(r1 + 8)   -- load allocation size from context
            Insn::ldx_h(R2, R1, 8),
            // r2 += 16                -- account for fixed per-event overhead
            Insn::add64_imm(R2, SMALL_ALLOC_OVERHEAD),
            // if r2 != 4096 goto +2   -- not exactly at the threshold, check range below
            Insn::jne_imm(R2, LARGE_ALLOC_THRESHOLD, 2),
            // r0 = 2                  -- verdict: flagged (large allocation)
            Insn::mov64_imm(R0, 2),
            // goto +1
            Insn {
                code: BPF_JMP,
                dst_reg: 0,
                src_reg: 0,
                off: 1,
                imm: 0,
            },
            // r0 = 1                  -- verdict: recorded (normal allocation)
            Insn::mov64_imm(R0, 1),
            // exit
            Insn::exit(),
        ];

        Self {
            name: "anima_memory_trace".to_string(),
            bytecode: assemble(&insns),
            maps: vec![EbpfMap {
                name: "memory_events".to_string(),
                map_type: EbpfMapType::PerCpuArray,
                key_size: 4,
                value_size: 128,
            }],
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every eBPF instruction is exactly 8 bytes; bytecode must be a whole multiple.
    fn assert_well_formed(bytecode: &[u8]) {
        assert!(!bytecode.is_empty(), "bytecode must not be empty");
        assert_eq!(
            bytecode.len() % 8,
            0,
            "bytecode must be a multiple of 8 bytes"
        );
    }

    #[test]
    fn ebpf_program_generates_inference() {
        let prog = EbpfProgram::generate_inference_intercept();
        assert_eq!(prog.name, "anima_inference_intercept");
        assert!(!prog.maps.is_empty());
        assert_well_formed(&prog.bytecode);
    }

    #[test]
    fn ebpf_program_memory_trace() {
        let prog = EbpfProgram::generate_memory_trace();
        assert_eq!(prog.name, "anima_memory_trace");
        assert_eq!(prog.maps[0].map_type, EbpfMapType::PerCpuArray);
        assert_well_formed(&prog.bytecode);
    }

    #[test]
    fn inference_intercept_has_expected_instruction_count() {
        let prog = EbpfProgram::generate_inference_intercept();
        // 7 instructions: ldx, and64, jeq, mov, goto, mov, exit
        assert_eq!(prog.bytecode.len(), 7 * 8);
    }

    #[test]
    fn inference_intercept_first_instruction_is_ldx_w_ctx_load() {
        let prog = EbpfProgram::generate_inference_intercept();
        let insn = &prog.bytecode[0..8];
        // code = BPF_LDX | BPF_MEM | BPF_W = 0x01 | 0x60 | 0x00 = 0x61
        assert_eq!(insn[0], 0x61, "opcode byte must encode LDX|MEM|W");
        // dst_reg = r2 (low nibble), src_reg = r1 (high nibble)
        assert_eq!(insn[1], 0x12, "dst/src register nibble byte must be r2/r1");
        // offset = 0
        assert_eq!(i16::from_le_bytes([insn[2], insn[3]]), 0);
        // imm unused for LDX
        assert_eq!(i32::from_le_bytes([insn[4], insn[5], insn[6], insn[7]]), 0);
    }

    #[test]
    fn inference_intercept_second_instruction_is_and64_mask() {
        let prog = EbpfProgram::generate_inference_intercept();
        let insn = &prog.bytecode[8..16];
        // code = BPF_ALU64 | BPF_AND | BPF_K = 0x07 | 0x50 | 0x00 = 0x57
        assert_eq!(insn[0], 0x57, "opcode byte must encode ALU64|AND|K");
        assert_eq!(insn[1] & 0x0f, R2, "dst_reg must be r2");
        assert_eq!(
            i32::from_le_bytes([insn[4], insn[5], insn[6], insn[7]]),
            0xff
        );
    }

    #[test]
    fn inference_intercept_last_instruction_is_exit() {
        let prog = EbpfProgram::generate_inference_intercept();
        let last = &prog.bytecode[prog.bytecode.len() - 8..];
        // code = BPF_JMP | BPF_EXIT = 0x05 | 0x90 = 0x95
        assert_eq!(last[0], 0x95, "final instruction must be BPF_EXIT");
        assert_eq!(
            &last[1..8],
            &[0, 0, 0, 0, 0, 0, 0],
            "exit insn has no operands"
        );
    }

    #[test]
    fn inference_intercept_contains_mov64_r0_1_accept_verdict() {
        let prog = EbpfProgram::generate_inference_intercept();
        // Fourth instruction (index 3, bytes 24..32): mov64 r0, 1
        let insn = &prog.bytecode[24..32];
        // code = BPF_ALU64 | BPF_MOV | BPF_K = 0x07 | 0xb0 | 0x00 = 0xb7
        assert_eq!(insn[0], 0xb7, "opcode byte must encode ALU64|MOV|K");
        assert_eq!(insn[1] & 0x0f, R0, "dst_reg must be r0");
        assert_eq!(i32::from_le_bytes([insn[4], insn[5], insn[6], insn[7]]), 1);
    }

    #[test]
    fn memory_trace_has_expected_instruction_count() {
        let prog = EbpfProgram::generate_memory_trace();
        // 7 instructions: ldx, add64, jne, mov, goto, mov, exit
        assert_eq!(prog.bytecode.len(), 7 * 8);
    }

    #[test]
    fn memory_trace_first_instruction_is_ldx_h_ctx_load() {
        let prog = EbpfProgram::generate_memory_trace();
        let insn = &prog.bytecode[0..8];
        // code = BPF_LDX | BPF_MEM | BPF_H = 0x01 | 0x60 | 0x08 = 0x69
        assert_eq!(insn[0], 0x69, "opcode byte must encode LDX|MEM|H");
        assert_eq!(insn[1] & 0x0f, R2, "dst_reg must be r2");
        assert_eq!((insn[1] >> 4) & 0x0f, R1, "src_reg must be r1 (context)");
        assert_eq!(
            i16::from_le_bytes([insn[2], insn[3]]),
            8,
            "offset must be ctx+8"
        );
    }

    #[test]
    fn memory_trace_second_instruction_is_add64_overhead() {
        let prog = EbpfProgram::generate_memory_trace();
        let insn = &prog.bytecode[8..16];
        // code = BPF_ALU64 | BPF_ADD | BPF_K = 0x07 | 0x00 | 0x00 = 0x07
        assert_eq!(insn[0], 0x07, "opcode byte must encode ALU64|ADD|K");
        assert_eq!(i32::from_le_bytes([insn[4], insn[5], insn[6], insn[7]]), 16);
    }

    #[test]
    fn memory_trace_last_instruction_is_exit() {
        let prog = EbpfProgram::generate_memory_trace();
        let last = &prog.bytecode[prog.bytecode.len() - 8..];
        assert_eq!(last[0], 0x95, "final instruction must be BPF_EXIT");
    }

    #[test]
    fn all_instructions_are_from_known_opcode_set() {
        // Defensive structural check: every instruction's opcode byte must be one we
        // deliberately emit, catching accidental corruption/misencoding.
        let known_opcodes: &[u8] = &[
            0x61, // LDX|MEM|W
            0x69, // LDX|MEM|H
            0x57, // ALU64|AND|K
            0x07, // ALU64|ADD|K
            0xb7, // ALU64|MOV|K
            0x15, // JMP|JEQ|K
            0x55, // JMP|JNE|K
            0x05, // JMP|JA (bare goto, dst/src/imm all zero)
            0x95, // JMP|EXIT
        ];
        for prog in [
            EbpfProgram::generate_inference_intercept(),
            EbpfProgram::generate_memory_trace(),
        ] {
            for chunk in prog.bytecode.as_chunks::<8>().0 {
                assert!(
                    known_opcodes.contains(&chunk[0]),
                    "unexpected opcode byte 0x{:02x} in program {}",
                    chunk[0],
                    prog.name
                );
            }
        }
    }

    #[test]
    fn maps_still_describe_expected_shapes() {
        let inference = EbpfProgram::generate_inference_intercept();
        assert_eq!(inference.maps[0].name, "intercept_events");
        assert_eq!(inference.maps[0].key_size, 8);
        assert_eq!(inference.maps[0].value_size, 64);

        let memory = EbpfProgram::generate_memory_trace();
        assert_eq!(memory.maps[0].name, "memory_events");
        assert_eq!(memory.maps[0].key_size, 4);
        assert_eq!(memory.maps[0].value_size, 128);
    }
}
